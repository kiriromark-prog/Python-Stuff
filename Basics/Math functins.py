# For this lesson, we will be using the math module. 
# The math module contains many useful functions for performing mathematical operations. 
# To use the math module, you need to import it first.    

#the math module provides a variety of mathematical functions, including trigonometric functions, logarithmic functions, and more.
import math

pi = 3.14


# The round() function rounds a number to the nearest integer.
print(round(pi))  # Output: 3

# The ceil() function returns the smallest integer greater than or equal to a given number.
print(math.ceil(pi))  # Output: 4

# The floor() function returns the largest integer less than or equal to a given number.
print(math.floor(pi))  # Output: 3

# The abs() function returns the absolute value of a number.
print(abs(-7.25))  # Output: 7.25

# The pow() function returns the value of a number raised to the power of another number.
print(pow(pi, 2))  # Output: 9.8596

# The sqrt() function returns the square root of a number.
print(math.sqrt(16))  # Output: 4.0

# Lets try some more math functions:
x = 1
y = 2
z = 3

# The max() function returns the largest of the input values.
print(max(x, y, z))  # Output: 3

# The min() function returns the smallest of the input values.
print(min(x, y, z))  # Output: 1

